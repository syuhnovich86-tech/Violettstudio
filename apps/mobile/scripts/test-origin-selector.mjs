import assert from 'node:assert/strict';
import { OriginSelector } from '../src/api/networkOrigin.ts';
let now = 1000;
let direct = true;
let backup = true;
let probes = [];
const selector = new OriginSelector('direct', 'backup', async origin => { probes.push(origin); return origin === 'direct' ? direct : backup; }, () => now);
assert.equal(await selector.resolve(), 'direct');
assert.deepEqual(probes, ['direct']);
direct = false; now += 30001; probes = [];
assert.equal(await selector.resolve(), 'backup');
assert.deepEqual(probes, ['direct', 'backup']);
direct = true; now += 30001;
assert.equal(await selector.resolve(), 'direct');
direct = backup = false; selector.invalidate();
assert.equal(await selector.resolve(), 'direct');
backup = true; now += 5001;
assert.equal(await selector.resolve(), 'backup');
let calls = 0;
const concurrent = new OriginSelector('a', 'b', async () => { calls++; await new Promise(resolve => setTimeout(resolve, 10)); return true; });
assert.deepEqual(await Promise.all([concurrent.resolve(), concurrent.resolve()]), ['a', 'a']);
assert.equal(calls, 1);
console.log('Android origin fallback, recovery, offline and concurrent checks passed');
